CREATE DATABASE IF NOT EXISTS qlphongkhamnhakhoa
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE qlphongkhamnhakhoa;

CREATE TABLE IF NOT EXISTS TAI_KHOAN_NGUOI_DUNG (
  MaND INT AUTO_INCREMENT PRIMARY KEY,
  TenDN VARCHAR(50) NOT NULL UNIQUE,
  MatKhau VARCHAR(255) NOT NULL,
  VaiTro VARCHAR(20) NOT NULL,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG',
  NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_tknd_vaitro CHECK (VaiTro IN ('BENH_NHAN','BAC_SI','NHAN_VIEN','QUAN_TRI_VIEN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS BENH_NHAN (
  MaBN INT AUTO_INCREMENT PRIMARY KEY,
  MaND INT NULL UNIQUE,
  HoTen VARCHAR(100) NOT NULL,
  SDT VARCHAR(20) NULL,
  Email VARCHAR(100) NULL,
  DiaChi TEXT NULL,
  GioiTinh VARCHAR(10) NULL,
  NgaySinh DATE NULL,
  CONSTRAINT fk_benh_nhan_tai_khoan FOREIGN KEY (MaND) REFERENCES TAI_KHOAN_NGUOI_DUNG(MaND)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS BAC_SI (
  MaBS INT AUTO_INCREMENT PRIMARY KEY,
  MaND INT NOT NULL UNIQUE,
  HoTen VARCHAR(100) NOT NULL,
  SDT VARCHAR(20) NULL,
  Email VARCHAR(100) NULL,
  ChuyenMon VARCHAR(100) NULL,
  GioiThieu TEXT NULL,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG',
  CONSTRAINT fk_bac_si_tai_khoan FOREIGN KEY (MaND) REFERENCES TAI_KHOAN_NGUOI_DUNG(MaND)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS NHAN_VIEN (
  MaNV INT AUTO_INCREMENT PRIMARY KEY,
  MaND INT NOT NULL UNIQUE,
  HoTen VARCHAR(100) NOT NULL,
  SDT VARCHAR(20) NULL,
  Email VARCHAR(100) NULL,
  ChucVu VARCHAR(100) NULL,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG',
  CONSTRAINT fk_nhan_vien_tai_khoan FOREIGN KEY (MaND) REFERENCES TAI_KHOAN_NGUOI_DUNG(MaND)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS DICH_VU (
  MaDV INT AUTO_INCREMENT PRIMARY KEY,
  TenDV VARCHAR(100) NOT NULL,
  MoTa TEXT NULL,
  ThoiLuong INT NOT NULL,
  GiaDV DECIMAL(10,2) NOT NULL,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'DANG_AP_DUNG',
  CONSTRAINT ck_dv_thoiluong CHECK (ThoiLuong > 0),
  CONSTRAINT ck_dv_gia CHECK (GiaDV >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS LICH_LAM_VIEC (
  MaLLV INT AUTO_INCREMENT PRIMARY KEY,
  MaBS INT NOT NULL,
  NgayLamViec DATE NOT NULL,
  GioBatDau TIME NOT NULL,
  GioKetThuc TIME NOT NULL,
  BatDauNghi TIME NULL,
  KetThucNghi TIME NULL,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG',
  INDEX ix_llv_mabs_ngay (MaBS, NgayLamViec),
  CONSTRAINT fk_llv_bac_si FOREIGN KEY (MaBS) REFERENCES BAC_SI(MaBS),
  CONSTRAINT ck_llv_gio CHECK (GioBatDau < GioKetThuc),
  CONSTRAINT ck_llv_nghi CHECK (
    (BatDauNghi IS NULL AND KetThucNghi IS NULL) OR
    (BatDauNghi IS NOT NULL AND KetThucNghi IS NOT NULL AND BatDauNghi < KetThucNghi
     AND BatDauNghi >= GioBatDau AND KetThucNghi <= GioKetThuc)
  )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS LICH_HEN_KHAM (
  MaLH INT AUTO_INCREMENT PRIMARY KEY,
  MaBN INT NOT NULL,
  MaLLV INT NOT NULL,
  MaDV INT NOT NULL,
  MaNVTao INT NULL,
  NgayKham DATE NOT NULL,
  GioBatDau TIME NOT NULL,
  GioKetThuc TIME NOT NULL,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'CHO_XAC_NHAN',
  GhiChu TEXT NULL,
  NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX ix_lhk_mabn (MaBN),
  INDEX ix_lhk_mallv_ngay (MaLLV, NgayKham),
  INDEX ix_lhk_madv (MaDV),
  INDEX ix_lhk_mnvt (MaNVTao),
  CONSTRAINT fk_lhk_benh_nhan FOREIGN KEY (MaBN) REFERENCES BENH_NHAN(MaBN),
  CONSTRAINT fk_lhk_lich_lam_viec FOREIGN KEY (MaLLV) REFERENCES LICH_LAM_VIEC(MaLLV),
  CONSTRAINT fk_lhk_dich_vu FOREIGN KEY (MaDV) REFERENCES DICH_VU(MaDV),
  CONSTRAINT fk_lhk_nhan_vien FOREIGN KEY (MaNVTao) REFERENCES NHAN_VIEN(MaNV),
  CONSTRAINT ck_lhk_gio CHECK (GioBatDau < GioKetThuc)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS HO_SO_BENH_AN (
  MaHSBA INT AUTO_INCREMENT PRIMARY KEY,
  MaBN INT NOT NULL UNIQUE,
  TienSuBenh TEXT NULL,
  DiUng TEXT NULL,
  GhiChu TEXT NULL,
  NgayLap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'DANG_THEO_DOI',
  CONSTRAINT fk_hsba_benh_nhan FOREIGN KEY (MaBN) REFERENCES BENH_NHAN(MaBN)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS DOT_DIEU_TRI (
  MaDT INT AUTO_INCREMENT PRIMARY KEY,
  MaHSBA INT NOT NULL,
  MaBS INT NOT NULL,
  LyDoDieuTri VARCHAR(300) NULL,
  ChuanDoan TEXT NULL,
  KeHoachDieuTri TEXT NULL,
  NgayBatDau DATE NOT NULL,
  NgayKetThuc DATE NULL,
  TrangThai VARCHAR(20) NOT NULL DEFAULT 'DANG_DIEU_TRI',
  KetQuaTongKet TEXT NULL,
  INDEX ix_ddt_hsba (MaHSBA),
  INDEX ix_ddt_bacsi (MaBS),
  CONSTRAINT fk_ddt_hsba FOREIGN KEY (MaHSBA) REFERENCES HO_SO_BENH_AN(MaHSBA),
  CONSTRAINT fk_ddt_bacsi FOREIGN KEY (MaBS) REFERENCES BAC_SI(MaBS),
  CONSTRAINT ck_ddt_ngay CHECK (NgayKetThuc IS NULL OR NgayKetThuc >= NgayBatDau)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS LAN_KHAM (
  MaLKham INT AUTO_INCREMENT PRIMARY KEY,
  MaDT INT NOT NULL,
  MaBS INT NOT NULL,
  MaLH INT NULL UNIQUE,
  NgayGioKham DATETIME NOT NULL,
  LyDoKham VARCHAR(300) NULL,
  TrieuChung TEXT NULL,
  ChanDoan TEXT NULL,
  KetQuaKham TEXT NULL,
  HuongXuLy TEXT NULL,
  GhiChu TEXT NULL,
  TrangThaiLanKham VARCHAR(20) NOT NULL DEFAULT 'DA_TIEP_NHAN',
  NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX ix_lk_madt (MaDT),
  INDEX ix_lk_mabs (MaBS),
  CONSTRAINT fk_lk_dot_dieu_tri FOREIGN KEY (MaDT) REFERENCES DOT_DIEU_TRI(MaDT),
  CONSTRAINT fk_lk_bac_si FOREIGN KEY (MaBS) REFERENCES BAC_SI(MaBS),
  CONSTRAINT fk_lk_lich_hen FOREIGN KEY (MaLH) REFERENCES LICH_HEN_KHAM(MaLH)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS DICH_VU_LAN_KHAM (
  MaDVLK INT AUTO_INCREMENT PRIMARY KEY,
  MaLKham INT NOT NULL,
  MaDV INT NOT NULL,
  SoLuong INT NOT NULL DEFAULT 1,
  DonGiaApDung DECIMAL(10,2) NOT NULL,
  ThoiGianThucHien DATETIME NULL,
  GhiChu TEXT NULL,
  INDEX ix_dvlk_lk (MaLKham),
  INDEX ix_dvlk_dv (MaDV),
  CONSTRAINT fk_dvlk_lan_kham FOREIGN KEY (MaLKham) REFERENCES LAN_KHAM(MaLKham),
  CONSTRAINT fk_dvlk_dich_vu FOREIGN KEY (MaDV) REFERENCES DICH_VU(MaDV),
  CONSTRAINT ck_dvlk_sl CHECK (SoLuong > 0),
  CONSTRAINT ck_dvlk_gia CHECK (DonGiaApDung >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS DON_THUOC (
  MaDonThuoc INT AUTO_INCREMENT PRIMARY KEY,
  MaLKham INT NOT NULL UNIQUE,
  MaBS INT NOT NULL,
  NgayKeDon DATE NOT NULL,
  LoiDan TEXT NULL,
  GhiChu TEXT NULL,
  INDEX ix_dt_bacsi (MaBS),
  CONSTRAINT fk_dt_lan_kham FOREIGN KEY (MaLKham) REFERENCES LAN_KHAM(MaLKham),
  CONSTRAINT fk_dt_bac_si FOREIGN KEY (MaBS) REFERENCES BAC_SI(MaBS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CHI_TIET_DON_THUOC (
  MaCTDT INT AUTO_INCREMENT PRIMARY KEY,
  MaDonThuoc INT NOT NULL,
  TenThuoc VARCHAR(200) NOT NULL,
  SoLuong DECIMAL(10,2) NOT NULL,
  LieuLuong VARCHAR(100) NULL,
  CachDung VARCHAR(255) NULL,
  ThoiGianBatDau DATE NULL,
  ThoiGianKetThuc DATE NULL,
  INDEX ix_ctdt_don (MaDonThuoc),
  CONSTRAINT fk_ctdt_don_thuoc FOREIGN KEY (MaDonThuoc) REFERENCES DON_THUOC(MaDonThuoc),
  CONSTRAINT ck_ctdt_sl CHECK (SoLuong > 0),
  CONSTRAINT ck_ctdt_ngay CHECK (ThoiGianBatDau IS NULL OR ThoiGianKetThuc IS NULL OR ThoiGianKetThuc >= ThoiGianBatDau)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
